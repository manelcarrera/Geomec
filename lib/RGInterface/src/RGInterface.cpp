///////////////////////////////////////////////////////////////////////////////
//
///////////////////////////////////////////////////////////////////////////////
std::string RGInterface::Versioning::toString() const
{
   std::ostringstream msg;
   msg << name  << " "; 
   msg << major << ".";
   msg << minor;
   return msg.str();
}

