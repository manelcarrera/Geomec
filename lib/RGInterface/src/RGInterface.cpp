///////////////////////////////////////////////////////////////////////////////
RGInterface::RGInterface( const std::string & modelName, bool saveAsTxt  )
{
   if ( modelName.empty() )
   {
      throw Exception( "RGInterface::RGInterface empty model name specified" );
   }
   m_pimpl = new RGInterfaceImpl( modelName, saveAsTxt );
}

///////////////////////////////////////////////////////////////////////////////
// Documented in .h
///////////////////////////////////////////////////////////////////////////////
RGInterface::RGInterface( const std::string & modelName, const RGInterface & toCp, bool saveAsTxt )
{
   m_pimpl = new RGInterfaceImpl( modelName, toCp.m_pimpl, saveAsTxt );
}


