OIV2DLegend::OIV2DLegend()
    : m_textSize(12)
    , m_textSpacing(1.5f)
{
    setName ("OIV2DLegend");

    // Font settings and material for 2D annotations.
    m_font = new SoFont();
    m_font->name = "Arial";
    m_font->size = m_textSize;
    m_font->renderStyle = SoFont::TEXTURE;
    m_material = new SoMaterial();
    m_material->diffuseColor = SbColor(1,1,1);

    addChild( m_font );
    addChild( m_material );

    addPixelSpaceCamera( this, FALSE, TRUE ); // top left corner

    m_switch = new SoSwitch;
    addChild(m_switch);
    m_switch->whichChild = SO_SWITCH_ALL;
    m_switch->setName ("LegendSceneSwitch");

    SoResetTransform *pResetBbox = new SoResetTransform();
    pResetBbox->whatToReset = SoResetTransform::BBOX;
    addChild( pResetBbox );

    SoMarkerSet::addMarker(OIV2DMARKERINDEX, SbVec2s(32, 8), OIV2DMarkerBits);

    SoTranslation *baseTranslation = new SoTranslation();
    baseTranslation->setName("BaseTranslation");
    baseTranslation->translation = SbVec3f( 4, -20, 0 );
    m_switch->addChild( baseTranslation );
    m_legendSections = new SoGroup;
    m_switch->addChild(m_legendSections);
}


void OIV2DLegend::addItem( std::size_t index, const std::string & name, float red, float green, float blue )
{
    legendSection(index)->addItem (name, red, green, blue);
    updateSectionOffsets();
}

void OIV2DLegend::addLeader( std::size_t index, const std::string & leader )
{
    legendSection(index)->addLeader(leader);
    updateSectionOffsets();
}

void OIV2DLegend::addLegendSection()
{
    OIV2DLegendSection * legendSection = new OIV2DLegendSection;
    legendSection->clear();
    m_legendSections->addChild(legendSection);  

}

OIV2DLegendSection * OIV2DLegend::legendSection( std::size_t index ) const
{
    assert (m_legendSections && index < m_legendSections->getNumChildren());
    return static_cast<OIV2DLegendSection*> (m_legendSections->getChild(index));
}

int OIV2DLegend::numLegendSections()
{
    return m_legendSections->getNumChildren();
}

void OIV2DLegend::clear()
{
    for (int i = 0; i < numLegendSections(); ++i)
    {
        clear(i);
    }
}

void OIV2DLegend::clear( std::size_t index )
{
    legendSection(index)->clear();
    updateSectionOffsets();
}

void OIV2DLegend::updateSectionOffsets()
{
    int offset = 0;
    for (int i = 1; i < numLegendSections(); ++i)
    {
        int numLines = getNumLines(i - 1);
        offset += numLines;
        if (numLines) ++offset; // separator line
        legendSection(i)->setOffset(offset);
    }
}

int OIV2DLegend::getNumLines( int i )
{
    return legendSection(i)->getNumLines();
}

void OIV2DLegend::setForegroundColor( float textColor[3] )
{
    m_material->diffuseColor = SbColor(textColor);
}
